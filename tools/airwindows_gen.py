#!/usr/bin/env python3
"""Write the C++ that lets the rack engine build Airwindows' plugins: one wrapper per plugin, and the table.

    tools/airwindows_gen.py OUTDIR

Each Airwindows plugin (vendor/airwindows/plugins/LinuxVST/src/NAME/{NAME.h,NAME.cpp,NAMEProc.cpp}) is a
class in the global namespace, and the plugins share names (`kParamA`, `kNumPrograms`, helpers) that would
clash if they were linked into one program. So each is compiled in a translation unit of its own, inside a
namespace, against the host stand-in in native/rack/aw/audioeffectx.h. Nothing is copied: the wrappers
`#include` the vendored files in place. OUTDIR gets aw_NAME.cc for each and aw_table.cc, the list the
AIRWINDOWS module reads (name and a factory, sorted by name without regard to case).
"""
import os
import sys

root = os.path.normpath(os.path.join(os.path.dirname(os.path.abspath(__file__)), ".."))
src = os.path.join(root, "vendor", "airwindows", "plugins", "LinuxVST", "src")
out = sys.argv[1]
os.makedirs(out, exist_ok=True)

names = sorted((d for d in os.listdir(src)
                if all(os.path.isfile(os.path.join(src, d, d + s)) for s in (".h", ".cpp", "Proc.cpp"))),
               key=lambda s: (s.lower(), s))


def write_if_changed(path, text):
    # Keep timestamps: the build recompiles only what changed.
    try:
        with open(path) as f:
            if f.read() == text:
                return
    except OSError:
        pass
    with open(path, "w") as f:
        f.write(text)


for n in names:
    d = os.path.join(src, n)
    write_if_changed(os.path.join(out, "aw_%s.cc" % n), f'''// Generated by tools/airwindows_gen.py: Airwindows {n} (MIT, Chris Johnson), compiled in place.
#include "audioeffectx.h"
namespace awx_{n} {{
#include "{d}/{n}.h"
#include "{d}/{n}.cpp"
#include "{d}/{n}Proc.cpp"
}}
AudioEffect* aw_make_{n}() {{ return awx_{n}::createEffectInstance(nullptr); }}
''')

lines = ['// Generated by tools/airwindows_gen.py.', '#include "aw_table.h"']
lines += ["AudioEffect* aw_make_%s();" % n for n in names]
lines.append("const AwEntry aw_entries[] = {")
lines += ['  {"%s", aw_make_%s},' % (n, n) for n in names]
lines.append("};")
lines.append("const int aw_count = %d;" % len(names))
write_if_changed(os.path.join(out, "aw_table.cc"), "\n".join(lines) + "\n")
print(len(names), "plugins", file=sys.stderr)
